def build_flat_index(categories=None):
    """Build a flat searchable list of all symbols with category context."""
    if categories is None:
        categories = CATEGORIES

    flat = []
    for cat in categories:
        for sub in cat['subcategories']:
            for sym in sub['symbols']:
                flat.append({
                    'char': sym['char'],
                    'name': sym['name'],
                    'unicode': sym['unicode'],
                    'category_id': cat['id'],
                    'category_name': cat['name'],
                    'subcategory_id': sub['id'],
                    'subcategory_name': sub['name'],
                })
    return flat


def get_total_symbol_count(categories=None):
    """Return total number of symbols across all categories."""
    if categories is None:
        categories = CATEGORIES
    return sum(len(sub['symbols']) for cat in categories for sub in cat['subcategories'])


def get_category_stats(categories=None):
    """Return list of (category_name, total_symbols) tuples."""
    if categories is None:
        categories = CATEGORIES
    return [
        (cat['name'], sum(len(sub['symbols']) for sub in cat['subcategories']))
        for cat in categories
    ]
